import Foundation

enum PHPFPMConfigurationError: Error, Equatable, LocalizedError {
    case invalidPath(String)
    case invalidPoolName(String)
    case invalidEnvironmentKey(String)
    case invalidEnvironmentValue(String)
    case invalidLimit(String)

    var errorDescription: String? {
        switch self {
        case .invalidPath(let path):
            return "The path is not safe for a php-fpm config: \(path)."
        case .invalidPoolName(let name):
            return "The pool name is not valid: \(name)."
        case .invalidEnvironmentKey(let key):
            return "The environment variable name is not valid: \(key)."
        case .invalidEnvironmentValue(let key):
            return "The value for \(key) contains characters php-fpm cannot represent."
        case .invalidLimit(let message):
            return message
        }
    }
}

/// A single app-owned php-fpm pool: one per site, listening on a Unix socket under the site's
/// directory, with conservative process limits and an explicit environment allowlist.
struct PHPFPMPoolConfiguration: Equatable, Sendable {
    let poolName: String
    let socketPath: String
    let documentRootPath: String
    let errorLogPath: String
    let pidPath: String
    let maxChildren: Int
    let maxRequests: Int
    let requestTerminateTimeoutSeconds: Int
    /// The only environment variables the worker sees (`clear_env = yes`; never the app's environment).
    let environment: [String: String]

    init(
        poolName: String = "www",
        socketPath: String,
        documentRootPath: String,
        errorLogPath: String,
        pidPath: String,
        maxChildren: Int = 5,
        maxRequests: Int = 500,
        requestTerminateTimeoutSeconds: Int = 60,
        environment: [String: String]
    ) {
        self.poolName = poolName
        self.socketPath = socketPath
        self.documentRootPath = documentRootPath
        self.errorLogPath = errorLogPath
        self.pidPath = pidPath
        self.maxChildren = maxChildren
        self.maxRequests = maxRequests
        self.requestTerminateTimeoutSeconds = requestTerminateTimeoutSeconds
        self.environment = environment
    }
}

/// Builds the explicit allowlist a pool worker sees. Only a fixed set of harmless variables plus the
/// runtime's `bin` directory are forwarded, so app secrets in the process environment never leak in.
enum PHPFPMEnvironment {
    static let allowedKeys = ["HOME", "TMPDIR", "LANG"]

    static func allowlist(
        runtimeBinPath: String,
        from environment: [String: String]
    ) -> [String: String] {
        var allowlist: [String: String] = [:]
        for key in allowedKeys {
            if let value = environment[key], !value.isEmpty {
                allowlist[key] = value
            }
        }
        let systemPath = environment["PATH"].flatMap { $0.isEmpty ? nil : $0 } ?? "/usr/bin:/bin:/usr/sbin:/sbin"
        allowlist["PATH"] = runtimeBinPath + ":" + systemPath
        allowlist["CE_RUNTIME_PATH"] = runtimeBinPath
        return allowlist
    }
}

/// Stateless php-fpm pool config builder. All paths must be app-controlled.
enum PHPFPMConfigurationBuilder {
    static func configuration(_ configuration: PHPFPMPoolConfiguration) throws -> String {
        try validate(configuration)

        var lines = poolLines(configuration)
        lines.append(contentsOf: try environmentLines(configuration.environment))
        lines.append(contentsOf: adminLines(configuration))
        return lines.joined(separator: "\n") + "\n"
    }

    private static func poolLines(_ configuration: PHPFPMPoolConfiguration) -> [String] {
        [
            "; Generated by Nodal IDE — do not edit. One pool per local domain site.",
            "[global]",
            "daemonize = no",
            "pid = \(configuration.pidPath)",
            "error_log = \(configuration.errorLogPath)",
            "",
            "[\(configuration.poolName)]",
            "listen = \(configuration.socketPath)",
            "listen.mode = 0600",
            "listen.backlog = 128",
            "",
            "pm = dynamic",
            "pm.max_children = \(configuration.maxChildren)",
            "pm.start_servers = \(startServers(maxChildren: configuration.maxChildren))",
            "pm.min_spare_servers = 1",
            "pm.max_spare_servers = \(maxSpareServers(maxChildren: configuration.maxChildren))",
            "pm.max_requests = \(configuration.maxRequests)",
            "request_terminate_timeout = \(configuration.requestTerminateTimeoutSeconds)s",
            "",
            "chdir = \(configuration.documentRootPath)",
            "catch_workers_output = yes",
            "clear_env = yes"
        ]
    }

    private static func environmentLines(_ environment: [String: String]) throws -> [String] {
        try environment
            .sorted { $0.key < $1.key }
            .map { "env[\(try validate(key: $0.key))] = \"\(try escape(value: $0.value, for: $0.key))\"" }
    }

    private static func adminLines(_ configuration: PHPFPMPoolConfiguration) -> [String] {
        [
            "",
            "php_admin_value[error_log] = \(configuration.errorLogPath)",
            "php_admin_flag[log_errors] = on",
            "",
            "; Development-safe opcache: revalidate every request so edits take effect immediately.",
            "php_admin_flag[opcache.enable] = on",
            "php_admin_flag[opcache.enable_cli] = on",
            "php_admin_flag[opcache.validate_timestamps] = on",
            "php_admin_value[opcache.revalidate_freq] = 0"
        ]
    }

    private static func validate(_ configuration: PHPFPMPoolConfiguration) throws {
        try validate(path: configuration.socketPath)
        try validate(path: configuration.documentRootPath)
        try validate(path: configuration.errorLogPath)
        try validate(path: configuration.pidPath)
        try validate(poolName: configuration.poolName)

        guard (1...64).contains(configuration.maxChildren) else {
            throw PHPFPMConfigurationError.invalidLimit("pm.max_children must be between 1 and 64.")
        }
        guard configuration.maxRequests > 0 else {
            throw PHPFPMConfigurationError.invalidLimit("pm.max_requests must be greater than 0.")
        }
        guard configuration.requestTerminateTimeoutSeconds > 0 else {
            throw PHPFPMConfigurationError.invalidLimit("request_terminate_timeout must be greater than 0.")
        }
    }

    private static func startServers(maxChildren: Int) -> Int {
        min(2, max(1, maxChildren))
    }

    private static func maxSpareServers(maxChildren: Int) -> Int {
        max(1, min(3, maxChildren))
    }

    // MARK: - Validation

    private static func validate(path: String) throws {
        guard !path.isEmpty else {
            throw PHPFPMConfigurationError.invalidPath(path)
        }
        let forbidden = CharacterSet(charactersIn: " \t\n\r\"'`;{}$#\\")
        guard path.unicodeScalars.allSatisfy({ !forbidden.contains($0) }) else {
            throw PHPFPMConfigurationError.invalidPath(path)
        }
    }

    private static func validate(poolName: String) throws {
        let allowed = CharacterSet(charactersIn: "abcdefghijklmnopqrstuvwxyz0123456789_")
        guard !poolName.isEmpty, poolName.unicodeScalars.allSatisfy(allowed.contains) else {
            throw PHPFPMConfigurationError.invalidPoolName(poolName)
        }
    }

    @discardableResult
    private static func validate(key: String) throws -> String {
        guard let first = key.first, first.isLetter || first == "_" else {
            throw PHPFPMConfigurationError.invalidEnvironmentKey(key)
        }
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "_"))
        guard key.unicodeScalars.allSatisfy(allowed.contains) else {
            throw PHPFPMConfigurationError.invalidEnvironmentKey(key)
        }
        return key
    }

    private static func escape(value: String, for key: String) throws -> String {
        guard !value.contains(where: \.isNewline) else {
            throw PHPFPMConfigurationError.invalidEnvironmentValue(key)
        }
        return value
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
    }
}
