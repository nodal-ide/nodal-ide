//
//  PHPDebugEnvironment.swift
//  CodeEdit
//
//  Prepares an Xdebug ini (via PHP_INI_SCAN_DIR) so every request is debugged.
//

import Foundation

/// Xdebug's `start_with_request` cannot be set through `XDEBUG_CONFIG` (it is ignored), so we write a
/// real `.ini` and add its directory to `PHP_INI_SCAN_DIR`. Unlike a URL trigger, this debugs **every**
/// request (GET and POST) without touching application code.
enum PHPDebugEnvironment {
    static var directory: URL {
        FileManager.default.homeDirectoryForCurrentUser
            .appending(path: "Library/Application Support/Nodal/php-debug", directoryHint: .isDirectory)
    }

    static var iniURL: URL { directory.appending(path: "zz-codeedit-xdebug.ini") }

    /// Writes the Xdebug ini for `clientPort` and returns its directory, or `nil` on failure.
    @discardableResult
    static func prepare(clientPort: Int) -> URL? {
        let contents = """
        ; Generated by CodeEdit for PHP debugging — safe to delete.
        xdebug.mode=debug
        xdebug.start_with_request=yes
        xdebug.client_port=\(clientPort)

        """
        do {
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            try contents.write(to: iniURL, atomically: true, encoding: .utf8)
            return directory
        } catch {
            return nil
        }
    }

    /// The compiled-in default ini scan directory for a PHP executable (`PHP_CONFIG_FILE_SCAN_DIR`).
    static func defaultScanDirectory(phpExecutable: String?) -> String? {
        let executable = phpExecutable ?? "php"
        let output = RuntimeShell.run("'\(executable)' -r 'echo PHP_CONFIG_FILE_SCAN_DIR;' 2>/dev/null")
        let value = output.trimmingCharacters(in: .whitespacesAndNewlines)
        return value.isEmpty ? nil : value
    }
}
